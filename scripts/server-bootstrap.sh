#!/usr/bin/env bash
#
# One-time server setup for the portfolio stack. Run it ON THE SERVER:
#
#   bash server-bootstrap.sh
#
# It creates ~/stacks/portfolio-site/.env with freshly generated secrets and
# checks the things that silently break a first deploy. It never touches other
# stacks, and it is safe to re-run: an existing .env is left alone.
set -euo pipefail

STACK_DIR="${DEPLOY_PATH:-$HOME/stacks/portfolio-site}"
SITE_HOST="${SITE_HOST:-vbroendum.com}"
API_HOST="${API_HOST:-api.vbroendum.com}"
TRAEFIK_NETWORK="${TRAEFIK_NETWORK:-traefik-public}"

say() { printf '\n\033[1m%s\033[0m\n' "$*"; }
ok()  { printf '  ok    %s\n' "$*"; }
warn() { printf '  warn  %s\n' "$*"; }
die() { printf '  FAIL  %s\n' "$*" >&2; exit 1; }

say "1. preflight"

command -v docker >/dev/null || die "docker is not installed"
ok "docker $(docker --version | awk '{print $3}' | tr -d ,)"

[ "$(docker info --format '{{.Swarm.LocalNodeState}}')" = "active" ] \
  || die "this node is not in swarm mode (docker swarm init)"
ok "swarm is active"

docker network inspect "$TRAEFIK_NETWORK" >/dev/null 2>&1 \
  || die "network '$TRAEFIK_NETWORK' not found - is Traefik running?"
ok "network $TRAEFIK_NETWORK exists"

if docker service ls --format '{{.Name}}' | grep -q '^traefik'; then
  ok "traefik is running"
else
  warn "no traefik service found; routing will not work until it is up"
fi

say "2. stack directory"

mkdir -p "$STACK_DIR"
ok "$STACK_DIR"

say "3. environment file"

if [ -f "$STACK_DIR/.env" ]; then
  warn ".env already exists - leaving it untouched"
  warn "delete it first if you want fresh secrets (this logs you out of /admin)"
else
  umask 077
  cat > "$STACK_DIR/.env" <<EOF
# Generated by server-bootstrap.sh on $(date -Is)
# Secrets live here, on the server, and never in CI or git.

# ---- database ----
POSTGRES_USER=portfolio
POSTGRES_DB=portfolio
POSTGRES_PASSWORD=$(openssl rand -hex 24)

# ---- sessions ----
# Rotating JWT_SECRET signs everyone out; nothing else is affected.
JWT_SECRET=$(openssl rand -base64 48 | tr -d '\n')
SESSION_TTL=168h
COOKIE_DOMAIN=.${SITE_HOST}

# ---- public URLs ----
SITE_HOST=${SITE_HOST}
API_HOST=${API_HOST}
PUBLIC_SITE_URL=https://${SITE_HOST}
PUBLIC_API_URL=https://${API_HOST}

# ---- limits ----
MAX_UPLOAD_BYTES=26214400
EOF
  chmod 600 "$STACK_DIR/.env"
  ok "wrote $STACK_DIR/.env with generated secrets (mode 600)"
fi

say "4. what is left for you"

cat <<EOF
  DNS (Cloudflare), both pointing at this server:
      ${SITE_HOST}       A/AAAA   proxied
      ${API_HOST}        A/AAAA   proxied
    Traefik uses the Cloudflare DNS-01 challenge, so proxied records are fine.
    Set Cloudflare SSL mode to "Full (strict)".

  GitHub -> Settings -> Secrets and variables -> Actions

    Secrets:
      DEPLOY_HOST      this server's hostname or IP
      DEPLOY_USER      $(whoami)
      DEPLOY_SSH_KEY   private half of a key in ~/.ssh/authorized_keys here

    Variables:
      PUBLIC_SITE_URL  https://${SITE_HOST}
      PUBLIC_API_URL   https://${API_HOST}
      DEPLOY_PATH      ${STACK_DIR}

  Then push to main. The first deploy pulls the images and starts the stack.

  AFTER the first deploy has gone green (there is no container before then),
  copy scripts/adminctl.sh into ${STACK_DIR} and run:
      cd ${STACK_DIR} && ./adminctl.sh create-user -email you@example.com
EOF

say "done"
